// Bundle src/mcap.worker.ts (with @mcap/core) into a single self-contained string
// and emit it as src/generatedWorkerSource.ts. The panel imports that string and
// launches the worker from a Blob URL, so the worker + its deps travel inside the
// extension bundle (no separate worker chunk to resolve from the app sandbox).

import { build } from "esbuild";
import { writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const root = dirname(dirname(fileURLToPath(import.meta.url)));

const result = await build({
  entryPoints: [join(root, "src/mcap.worker.ts")],
  bundle: true,
  format: "iife",
  platform: "browser",
  target: "es2020",
  write: false,
  legalComments: "none",
});

const code = result.outputFiles[0].text;
const out =
  "// AUTO-GENERATED by scripts/bundle-worker.mjs. Do not edit by hand.\n" +
  "// Bundled Web Worker (mcap.worker.ts + @mcap/core) inlined as a string so it\n" +
  "// travels inside the extension bundle and runs from a Blob URL.\n" +
  `export const MCAP_WORKER_SOURCE = ${JSON.stringify(code)};\n`;

writeFileSync(join(root, "src/generatedWorkerSource.ts"), out);
console.log(`Bundled worker -> src/generatedWorkerSource.ts (${code.length} bytes)`);
